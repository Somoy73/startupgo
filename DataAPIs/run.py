#!/usr/bin/env python3
"""Run the scrapers.

  python3 run.py                       run every scraper that needs no key (default params)
  python3 run.py openalex gbif         run only these
  python3 run.py openalex search="kelp" per-page=10    override params (key=value after ONE name)
  python3 run.py --all                 also try key/paid ones (skipped if env key missing)
  python3 run.py --list                list scrapers
  python3 run.py --docs                regenerate PARAMETERS.md
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import common  # noqa: E402
import s1_startups_registries, s2_funding_procurement_patents, s3_news_search_market, s4_eu, s5_people_jobs  # noqa: E402,F401

OUT = Path(__file__).parent / "data"
MAX_LIST, MAX_STR = 10, 600


def trim(o, depth=0):
    """Keep samples small: cap lists/strings/dict size."""
    if isinstance(o, list):
        return [trim(x, depth + 1) for x in o[:MAX_LIST]] + ([f"... +{len(o) - MAX_LIST} more"] if len(o) > MAX_LIST else [])
    if isinstance(o, dict):
        items = list(o.items())
        return {k: trim(v, depth + 1) for k, v in items[:40]}
    if isinstance(o, str) and len(o) > MAX_STR:
        return o[:MAX_STR] + f"... [{len(o)} chars]"
    return o


def parse_kv(args):
    out = {}
    for a in args:
        k, v = a.split("=", 1)
        out[k] = int(v) if v.isdigit() else v
    return out


def run_one(s, overrides=None):
    kw = {**s.defaults, **(overrides or {})}
    t = time.time()
    try:
        data = s.fn(**kw)
        full = len(json.dumps(data, default=str))
        OUT.mkdir(exist_ok=True)
        (OUT / f"{s.name}.json").write_text(json.dumps({"params": kw, "full_size_bytes": full, "sample": trim(data)}, indent=2, ensure_ascii=False, default=str))
        return "ok", f"{full:,} bytes, {time.time() - t:.1f}s"
    except common.Skipped as e:
        return "skipped", str(e)
    except NotImplementedError as e:
        return "stub", str(e)
    except Exception as e:  # noqa: BLE001
        return "error", str(e)[:200]


def docs():
    lines = ["# Data API scrapers: sources and parameters\n",
             "Generated by `python3 run.py --docs`. `Default` = what the sample run sends. All listed params can be passed as `key=value`.\n"]
    sec = None
    for s in common.REGISTRY:
        if s.section != sec:
            sec = s.section
            lines.append(f"\n## {sec}\n")
        lines.append(f"### {s.name}  ·  {s.access}\n")
        lines.append(f"`{s.endpoint}`  \n{s.use}" + (f"  \n_{s.notes}_" if s.notes else "") + "\n")
        if s.params:
            lines += ["| Parameter | Meaning |", "|---|---|"] + [f"| `{k}` | {v} |" for k, v in s.params.items()]
        if s.defaults:
            lines.append(f"\nDefault: `{json.dumps(s.defaults, ensure_ascii=False)}`")
        lines.append("")
    Path(__file__).with_name("PARAMETERS.md").write_text("\n".join(lines))
    print("wrote PARAMETERS.md")


def main(argv):
    if "--docs" in argv:
        return docs()
    if "--list" in argv:
        for s in common.REGISTRY:
            print(f"{s.access:5} {s.name:30} {s.endpoint}")
        return
    run_all = "--all" in argv
    names = [a for a in argv if not a.startswith("--") and "=" not in a]
    overrides = parse_kv([a for a in argv if "=" in a and not a.startswith("--")])
    todo = [s for s in common.REGISTRY if (s.name in names if names else (run_all or s.access == "free"))]
    summary = {}
    for s in todo:
        status, info = run_one(s, overrides if len(names) == 1 else None)
        summary[s.name] = {"status": status, "info": info, "access": s.access}
        print(f"[{status:7}] {s.name:30} {info}")
        if s.slow and status == "ok":
            time.sleep(6)
    if not names:
        OUT.mkdir(exist_ok=True)
        (OUT / "_summary.json").write_text(json.dumps(summary, indent=2))
    c = {}
    for v in summary.values():
        c[v["status"]] = c.get(v["status"], 0) + 1
    print(c)


if __name__ == "__main__":
    main(sys.argv[1:])
